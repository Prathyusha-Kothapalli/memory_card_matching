export function getNatureById(id) {
  return NATURE_DATABASE.find(item => item.id === id) || NATURE_DATABASE[0];
}

export function filterNatureByRarity(rarity) {
  return NATURE_DATABASE.filter(item => item.rarity.toLowerCase() === rarity.toLowerCase());
}

