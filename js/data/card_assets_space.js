export function getSpaceById(id) {
  return SPACE_DATABASE.find(item => item.id === id) || SPACE_DATABASE[0];
}

export function filterSpaceByRarity(rarity) {
  return SPACE_DATABASE.filter(item => item.rarity.toLowerCase() === rarity.toLowerCase());
}

